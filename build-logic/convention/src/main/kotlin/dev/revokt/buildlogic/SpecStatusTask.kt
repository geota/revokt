package dev.revokt.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.util.Locale

/**
 * `./gradlew specStatus` (CONTRIBUTING §2): the spec's §9 fixture inventory and §11 deliverables against the test
 * tree, written to docs/dev/status.md. In check mode the committed file must be current and the implemented-fixture
 * count may not decrease (a ratchet, CONTRIBUTING §3).
 *
 * Test names carry `<list> (<id>)`, e.g. `walker (k) same-key decoy with garbage signature` (CONTRIBUTING §6).
 */
abstract class SpecStatusTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val spec: RegularFileProperty

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val testRoots: ConfigurableFileCollection

    /** Generate mode: the file to write. */
    @get:OutputFile
    @get:Optional
    abstract val output: RegularFileProperty

    /** Check mode: the committed file to compare against. */
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val committed: RegularFileProperty

    @get:Input
    abstract val checkOnly: Property<Boolean>

    /** The D8 gap over the CT seed corpus (spec §9.2), as RecordsTest records it per matrix JDK; absent before #64. */
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val ctSeedGap: RegularFileProperty

    @get:Internal
    abstract val rootDir: DirectoryProperty

    data class FixtureList(val name: String, val bulletPrefix: String)

    private val lists = listOf(
        FixtureList("data-path", "- **Data-path fixtures**"),
        FixtureList("walker", "- **Walker fixtures**"),
    )

    @TaskAction
    fun run() {
        val specText = spec.get().asFile.readText()
        val implementedNames = collectTestNames()
        val sections = lists.map { list -> list to fixtureIds(specText, list.bulletPrefix) }
        val deliverables = milestoneRows(specText)

        val sb = StringBuilder()
        sb.appendLine("<!-- Generated by ./gradlew specStatus; do not edit. A stale file fails check (CONTRIBUTING §2). -->")
        sb.appendLine("# Spec status")
        sb.appendLine()
        var implementedTotal = 0
        var total = 0
        for ((list, ids) in sections) {
            val done = ids.filter { id -> implementedNames.any { it.startsWith("${list.name} ($id)") } }
            implementedTotal += done.size
            total += ids.size
            sb.appendLine("## ${list.name} fixtures: ${done.size} / ${ids.size} implemented")
            sb.appendLine()
            for (id in ids) {
                val mark = if (id in done) "x" else " "
                sb.appendLine("- [$mark] ($id)")
            }
            sb.appendLine()
        }
        sb.appendLine("## §11 deliverables (by milestone)")
        sb.appendLine()
        for ((milestone, text) in deliverables) {
            sb.appendLine("### $milestone")
            sb.appendLine()
            sb.appendLine(text)
            sb.appendLine()
        }
        ctSeedGap.orNull?.asFile?.takeIf { it.isFile }?.let { appendGap(sb, it) }
        sb.appendLine("## Totals")
        sb.appendLine()
        sb.appendLine("- implemented-fixtures: $implementedTotal")
        sb.appendLine("- fixtures-in-spec: $total")
        val rendered = sb.toString()

        if (checkOnly.get()) {
            val out = committed.orNull?.asFile
            if (out == null || !out.isFile) throw GradleException("specStatusCheck: docs/dev/status.md is missing; run ./gradlew specStatus and commit it.")
            val committed = out.readText()
            val committedCount = Regex("- implemented-fixtures: (\\d+)").find(committed)?.groupValues?.get(1)?.toInt() ?: 0
            if (implementedTotal < committedCount) {
                throw GradleException(
                    "specStatusCheck: implemented fixtures dropped from $committedCount to $implementedTotal. The count is a ratchet (CONTRIBUTING §3): " +
                        "a fixture test is never deleted; quarantine it (CONTRIBUTING §6) or restore it.",
                )
            }
            if (committed != rendered) {
                throw GradleException("specStatusCheck: ${out.relativeTo(rootDir.get().asFile)} is stale; run ./gradlew specStatus and commit the result.")
            }
        } else {
            val out = output.get().asFile
            out.parentFile.mkdirs()
            out.writeText(rendered)
            logger.lifecycle("specStatus: $implementedTotal / $total fixtures implemented; wrote ${out.relativeTo(rootDir.get().asFile)}")
        }
    }

    /** The D8 gap section: per matrix JDK, the unexpired leaves it accepts, those in the D1 domain, the gap and its clauses. */
    private fun appendGap(sb: StringBuilder, file: File) {
        val lines = file.readLines()
        sb.appendLine("## D8 gap over the CT seed corpus (spec §9.2)")
        sb.appendLine()
        // `#` lines describe the record; `##` lines are notes for its maintainers only.
        lines.filter { it.startsWith("#") && !it.startsWith("##") }.forEach { sb.appendLine(it.removePrefix("#").trim()) }
        sb.appendLine()
        sb.appendLine("| JDK | unexpired leaves accepted | in the D1 domain | gap | rate | by clause |")
        sb.appendLine("|---|---|---|---|---|---|")
        for (line in lines.filter { it.isNotBlank() && !it.startsWith("#") }) {
            val (jdk, unexpired, inDomain, gap, clauses) = line.split('\t')
            val rate = if (unexpired.toLong() == 0L) 0.0 else gap.toDouble() / unexpired.toDouble()
            sb.appendLine("| $jdk | $unexpired | $inDomain | $gap | ${"%.2e".format(Locale.ROOT, rate)} | $clauses |")
        }
        sb.appendLine()
        sb.appendLine("The re-decision threshold is 10^-4 of the unexpired leaves (spec §9.2 D8 gap).")
        sb.appendLine()
    }

    private fun collectTestNames(): Set<String> {
        val backtick = Regex("fun `([^`]+)`")
        return testRoots.files.asSequence()
            .filter { it.isDirectory }
            .flatMap { root -> root.walkTopDown().filter { it.isFile && it.extension == "kt" && it.relativeTo(root).path.contains("Test") } }
            .flatMap { f -> backtick.findAll(f.readText()).map { it.groupValues[1] } }
            .toSet()
    }

    /** The ids `(a)`, `(s2)`, `(ad)` … inside one §9 bullet, in order of first appearance. */
    internal fun fixtureIds(specText: String, bulletPrefix: String): List<String> {
        val start = specText.indexOf(bulletPrefix)
        if (start < 0) return emptyList()
        val rest = specText.substring(start + bulletPrefix.length)
        val end = Regex("\\n- \\*\\*").find(rest)?.range?.first ?: rest.length
        val body = rest.substring(0, end)
        val seen = LinkedHashSet<String>()
        Regex("\\*{0,2}\\(([a-z]{1,2}\\d?)\\)\\*{0,2}").findAll(body).forEach { seen.add(it.groupValues[1]) }
        return seen.toList()
    }

    /** The §11 release table rows: milestone → scope cell. */
    internal fun milestoneRows(specText: String): List<Pair<String, String>> {
        val tableStart = specText.indexOf("| Release | Scope | Estimate |")
        if (tableStart < 0) return emptyList()
        return specText.substring(tableStart).lineSequence().drop(2)
            .takeWhile { it.startsWith("|") }
            .mapNotNull { line ->
                val cells = line.trim().trim('|').split("|").map { it.trim() }
                if (cells.size >= 2) cells[0] to cells[1] else null
            }
            .toList()
    }

    companion object {
        fun relative(file: File, root: File): String = file.relativeTo(root).path
    }
}
